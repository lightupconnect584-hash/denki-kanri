// 住所がエリアリスト（市町村名・県名の混在）にマッチするか
export function matchesServiceArea(areas: string[] | undefined | null, location: string): boolean {
  if (!areas || areas.length === 0 || !location) return false;
  for (const a of areas) {
    if (!a) continue;
    if (location.includes(a)) return true;
    // 県全域トークンは市町村に展開（住所に県名が無い場合に対応）
    const cities = PREF_CITIES[a];
    if (cities && cities.some((c) => location.includes(c))) return true;
  }
  return false;
}
